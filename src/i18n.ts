import type { Language } from './types';

export function tField(
  obj: Record<string, any> | null | undefined,
  base: string,
  lang: Language
): string {
  if (!obj) return '';
  const suffix = lang === 'ar' ? '_ar' : lang === 'es' ? '_es' : '_fr';
  const camelSuffix = lang === 'ar' ? 'Ar' : lang === 'es' ? 'Es' : 'Fr';
  return (
    obj[`${base}${suffix}`] ||
    obj[`${base}${camelSuffix}`] ||
    obj[`${base}_ar`] ||
    obj[`${base}Ar`] ||
    obj[base] ||
    ''
  );
}

